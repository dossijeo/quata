        perform public.quata_chat_edit_message_v2(
            '00000000-0000-0000-0000-000000000001',77,101,'different','chat-mutation-edit-000001'
        );
    exception when sqlstate '22023' then v_denied := true;
    end;
    if not v_denied then raise exception 'edit key reuse was accepted'; end if;

    perform public.quata_chat_delete_messages_v2(
        '00000000-0000-0000-0000-000000000001',77,array[102]::bigint[],'chat-mutation-delete-0001'
    );
    perform public.quata_chat_delete_messages_v2(
        '00000000-0000-0000-0000-000000000001',77,array[102]::bigint[],'chat-mutation-delete-0001'
    );
    if (select deleted_at is null from public.chat_messages where id=102) then
        raise exception 'delete was not applied';
    end if;
    if (select count(*) <> 1 from public.chat_events where event_type='messages_deleted' and payload->'message_ids' @> '[102]'::jsonb) then
        raise exception 'delete replay repeated its event';
    end if;
    if (select count(*) <> 2 from public.chat_message_mutation_receipts where completed_at is not null) then
        raise exception 'completed receipt count mismatch';
    end if;

