    if md5(pg_get_functiondef('public.quata_chat_edit_message(uuid,bigint,bigint,text)'::regprocedure)) <>
       (select value from public.legacy_function_fingerprint where name='edit') then
        raise exception 'legacy edit function changed';
    end if;
    if md5(pg_get_functiondef('public.quata_chat_delete_messages(uuid,bigint,bigint[])'::regprocedure)) <>
